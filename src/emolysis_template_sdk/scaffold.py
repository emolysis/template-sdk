"""`emo-template new`: write a minimal valid template skeleton for a shape and platform."""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

from .spec import DIALECTS, FORMAT_V0, PLATFORMS, SHAPES, template_id
from .validate import PathLike

_REQUIRES: dict[str, list[str]] = {
    "databricks": ["delta"],
    "fabric": ["delta"],
    "snowflake": [],
    "duckdb": [],
}

_SAMPLE_ROWS = "SELECT * FROM (VALUES (1, 'a'), (2, 'b')) AS t(id, name)"


def _manifest(shape: str, platform: str) -> str:
    title = f"{SHAPES[shape]} on {PLATFORMS[platform]}"
    return f"""format: {FORMAT_V0}
id: {template_id(shape, platform)}
shape: {shape}
platform: {platform}
version: 0.1.0
title: {title}
description: >-
  Starting point generated by emo-template new. Replace this with one paragraph on what
  the template does, what it expects from its inputs and what it writes.
entry: template.sql
slots:
  - name: source_table
    type: table
    required: true
    description: Table to read.
  - name: target_table
    type: table
    required: true
    description: Table to create or replace.
"""


def _entry(shape: str, platform: str) -> str:
    dialect = DIALECTS[platform]
    return f"""-- {SHAPES[shape]} on {PLATFORMS[platform]}, written in the {dialect} SQL dialect.
-- Starting point: copies the source into the target. Replace this with the shape's
-- logic, then update tests/basic so its expected tables match.
CREATE OR REPLACE TABLE {{{{ target_table }}}} AS
SELECT *
FROM {{{{ source_table }}}};
"""


def _cost(shape: str, platform: str) -> str:
    return f"""# Cost notes: {SHAPES[shape]} on {PLATFORMS[platform]}

Describe what this template costs to run on {PLATFORMS[platform]}: the compute it needs,
how cost grows with input size, and the settings that change it.
"""


def _constraints(platform: str) -> str:
    data = {
        "platform": platform,
        "profile_version": ">=1",
        "requires": _REQUIRES[platform],
        "forbids": [],
    }
    return json.dumps(data, indent=2) + "\n"


def new_template(shape: str, platform: str, directory: PathLike) -> Path:
    """Create a valid template skeleton for `shape` on `platform` in `directory`.

    The skeleton has a two-slot entry that copies a table, cost notes, profile
    constraints and one passing test case (`tests/basic`). Raises `ValueError` for an
    unknown shape or platform and `FileExistsError` when `directory` exists and is not
    an empty directory.
    """
    if shape not in SHAPES:
        raise ValueError(f"unknown shape {shape!r}; expected one of {', '.join(SHAPES)}")
    if platform not in PLATFORMS:
        raise ValueError(f"unknown platform {platform!r}; expected one of {', '.join(PLATFORMS)}")
    root = Path(directory)
    if root.exists() and (not root.is_dir() or any(root.iterdir())):
        raise FileExistsError(f"{root} exists and is not an empty directory")

    run = root / "tests" / "basic" / "runs" / "01"
    (run / "input").mkdir(parents=True)
    (run / "expected").mkdir(parents=True)
    (root / "template.yaml").write_text(_manifest(shape, platform), encoding="utf-8")
    (root / "template.sql").write_text(_entry(shape, platform), encoding="utf-8")
    (root / "cost.md").write_text(_cost(shape, platform), encoding="utf-8")
    (root / "profile_constraints.json").write_text(_constraints(platform), encoding="utf-8")
    (root / "tests" / "basic" / "slots.yaml").write_text(
        "source_table: source\ntarget_table: target\n", encoding="utf-8"
    )
    with duckdb.connect(":memory:") as con:
        for path in (run / "input" / "source.parquet", run / "expected" / "target.parquet"):
            target = str(path).replace("'", "''")
            con.execute(f"COPY ({_SAMPLE_ROWS}) TO '{target}' (FORMAT parquet)")
    return root
